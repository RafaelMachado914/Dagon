
package br.com.dagon;


public class Jogador {
    
    public int vida = 10;
    public int rodadas;

    public Jogador() {
    }

    
    public int getVida() {
        return vida;
    }

    public void setVida(int vida) {
        this.vida = vida;
    }

    public int getRodadas() {
        return rodadas;
    }

    public void setRodadas(int rodadas) {
        this.rodadas = rodadas;
    }
    
   
    
}
